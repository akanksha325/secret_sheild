import { SecretFinding, ScanMetrics } from '../types';

export function generateMarkdownReport(
  projectName: string,
  metrics: ScanMetrics,
  findings: SecretFinding[]
): string {
  const timestamp = new Date().toISOString();
  let md = `# SecretShield Security Audit Report

**Target Project:** \`${projectName}\`  
**Scan Timestamp:** \`${timestamp}\`  
**Engine:** SecretShield v2.4.0 (Entropy & Pattern Matcher)  
**Security Posture Score:** \`${metrics.securityScore}/100\`

---

## 1. Executive Summary

| Metric | Value |
| :--- | :--- |
| **Total Files Scanned** | ${metrics.scannedFiles} |
| **Lines of Code Analyzed** | ${metrics.linesAnalyzed.toLocaleString()} |
| **Total Exposed Secrets** | **${findings.length}** |
| **Critical Severity** | ${metrics.criticalCount} (Immediate Action Required) |
| **High Severity** | ${metrics.highCount} |
| **Medium Severity** | ${metrics.mediumCount} |
| **Low / Informational** | ${metrics.lowCount} |
| **Scan Execution Duration** | ${metrics.durationMs} ms |

---

## 2. Findings Summary Table

| ID | Risk | Secret Type | Location | Line | Masked Fingerprint | Confidence |
| :--- | :--- | :--- | :--- | :---: | :--- | :---: |
`;

  if (findings.length === 0) {
    md += `| - | - | *No exposed secrets detected. Clean repository.* | - | - | - | - |\n\n`;
  } else {
    findings.forEach((f) => {
      md += `| \`${f.id}\` | **${f.risk}** | ${f.secretType} | \`${f.filePath}\` | ${f.lineNumber} | \`${f.maskedValue.substring(0, 24)}...\` | ${f.confidence} |\n`;
    });
  }

  md += `\n---\n\n## 3. Detailed Remediation Procedures\n\n`;

  if (findings.length === 0) {
    md += `*No remediation required. Repository conforms to SecretShield Zero-Leak standard.*\n`;
  } else {
    findings.forEach((f, idx) => {
      md += `### ${idx + 1}. [${f.risk}] ${f.secretType} (\`${f.id}\`)
- **File Location:** \`${f.filePath}:${f.lineNumber}\`
- **Rule Identifier:** \`${f.ruleId}\`
- **Entropy Score:** \`${f.entropy}\`
- **Security Impact:** ${f.impact}

#### Step-by-Step Rotation:
${f.remediation.rotationSteps.map((step, sIdx) => `${sIdx + 1}. ${step}`).join('\n')}

#### Git History Clean Command:
\`\`\`bash
${f.remediation.gitPurgeCommand}
\`\`\`

#### Recommended Safe Implementation:
\`\`\`typescript
${f.remediation.safeAlternativeCode}
\`\`\`

---
`;
    });
  }

  md += `\n*Report automatically generated by SecretShield Scanner. All sensitive values have been masked.*`;
  return md;
}

export function generateCSVReport(
  projectName: string,
  findings: SecretFinding[]
): string {
  const headers = [
    'Finding ID',
    'Rule ID',
    'Risk Level',
    'Secret Type',
    'File Path',
    'Line Number',
    'Masked Value',
    'Confidence',
    'Entropy',
    'Status',
    'Impact Description',
  ];

  const rows = findings.map((f) => [
    `"${f.id}"`,
    `"${f.ruleId}"`,
    `"${f.risk}"`,
    `"${f.secretType}"`,
    `"${f.filePath}"`,
    f.lineNumber,
    `"${f.maskedValue.replace(/"/g, '""')}"`,
    `"${f.confidence}"`,
    f.entropy,
    `"${f.status}"`,
    `"${f.impact.replace(/"/g, '""')}"`,
  ]);

  return [headers.join(','), ...rows.map((r) => r.join(','))].join('\n');
}

export function generateSARIFReport(
  projectName: string,
  findings: SecretFinding[]
): string {
  const sarif = {
    $schema: 'https://raw.githubusercontent.com/oasis-tcs/sarif-spec/master/Schemata/sarif-schema-2.1.0.json',
    version: '2.1.0',
    runs: [
      {
        tool: {
          driver: {
            name: 'SecretShield',
            version: '2.4.0',
            informationUri: 'https://github.com/secretshield/security',
            rules: findings.map((f) => ({
              id: f.ruleId,
              name: f.secretType,
              shortDescription: { text: `Exposed ${f.secretType} in source code` },
              fullDescription: { text: f.impact },
              defaultConfiguration: {
                level: f.risk === 'CRITICAL' || f.risk === 'HIGH' ? 'error' : 'warning',
              },
            })),
          },
        },
        results: findings.map((f) => ({
          ruleId: f.ruleId,
          level: f.risk === 'CRITICAL' || f.risk === 'HIGH' ? 'error' : 'warning',
          message: {
            text: `Exposed ${f.secretType} detected with masked signature ${f.maskedValue.substring(0, 16)}...`,
          },
          locations: [
            {
              physicalLocation: {
                artifactLocation: { uri: f.filePath },
                region: { startLine: f.lineNumber },
              },
            },
          ],
        })),
      },
    ],
  };

  return JSON.stringify(sarif, null, 2);
}

export function triggerDownload(content: string, filename: string, mimeType: string) {
  const blob = new Blob([content], { type: mimeType });
  const url = URL.createObjectURL(blob);
  const a = document.createElement('a');
  a.href = url;
  a.download = filename;
  document.body.appendChild(a);
  a.click();
  document.body.removeChild(a);
  URL.revokeObjectURL(url);
}
